# 📋 CONFIGURAR SCRIPTS DE PACKAGE.JSON
setup_npm_scripts() {
    log "📋 Configurando scripts de NPM..."
    
    # Backend scripts
    cd "$DEVELOPMENT_PATH/backend"
    
    # Verificar si package.json existe
    if [ -f "package.json" ]; then
        # Agregar scripts de testing y CI/CD si no existen
        npm pkg set scripts.test="jest --testTimeout=10000"
        npm pkg set scripts.test:watch="jest --watch"
        npm pkg set scripts.test:coverage="jest --coverage"
        npm pkg set scripts.test:security="npm audit --audit-level moderate"
        npm pkg set scripts.test:api="node scripts/test_api_endpoints.js"
        npm pkg set scripts.lint="eslint . --ext .js"
        npm pkg set scripts.lint:fix="eslint . --ext .js --fix"
        npm pkg set scripts.db:migrate="node scripts/migrate.js"
        npm pkg set scripts.db:seed="node scripts/seed.js"
        npm pkg set scripts.start:dev="nodemon server.js"
        npm pkg set scripts.start:prod="node server.js"
        npm pkg set scripts.build="echo 'Backend build completed'"
        
        log "✅ Scripts de backend configurados"
    fi
    
    # Frontend scripts
    cd "$DEVELOPMENT_PATH/frontend"
    
    if [ -f "package.json" ]; then
        npm pkg set scripts.test="vitest run"
        npm pkg set scripts.test:watch="vitest"
        npm pkg set scripts.test:coverage="vitest run --coverage"
        npm pkg set scripts.lint="eslint src --ext .js,.jsx,.ts,.tsx"
        npm pkg set scripts.lint:fix="eslint src --ext .js,.jsx,.ts,.tsx --fix"
        npm pkg set scripts.build:production="vite build --mode production"
        npm pkg set scripts.preview="vite preview"
        
        log "✅ Scripts de frontend configurados"
    fi
}

# 🐳 CREAR DOCKERFILE PARA DESARROLLO
create_dockerfile() {
    log "🐳 Creando Dockerfile para desarrollo..."
    
    cat > "$DEVELOPMENT_PATH/Dockerfile.dev" << 'EOF'
# 🐳 Dockerfile para Desarrollo - Cober360
FROM node:18-alpine

# 📂 Crear directorio de trabajo
WORKDIR /app

# 📦 Copiar package.json files
COPY backend/package*.json ./backend/
COPY frontend/package*.json ./frontend/

# 🔧 Instalar dependencias
RUN cd backend && npm ci
RUN cd frontend && npm ci

# 📁 Copiar código fuente
COPY . .

# 🏗️ Build frontend
RUN cd frontend && npm run build

# 🚀 Exponer puerto
EXPOSE 4000

# 🎯 Comando por defecto
CMD ["npm", "run", "start:dev"]
EOF

    log "✅ Dockerfile de desarrollo creado"
}

# 📊 CONFIGURAR MONITOREO
setup_monitoring() {
    log "📊 Configurando herramientas de monitoreo..."
    
    # Crear script de health check
    cat > "$DEVELOPMENT_PATH/scripts/health_check.sh" << 'EOF'
#!/bin/bash

# 🏥 Health Check Script para Cober360

API_URL="http://localhost:4000/health"
TIMEOUT=10

echo "🏥 Verificando salud del sistema..."

# Test API
if curl -f -s --max-time $TIMEOUT "$API_URL" > /dev/null; then
    echo "✅ API: OK"
else
    echo "❌ API: FAIL"
    exit 1
fi

# Test Database
if mysqladmin ping -h localhost --silent; then
    echo "✅ Database: OK"
else
    echo "❌ Database: FAIL"
    exit 1
fi

# Test PM2
if pm2 list | grep -q "online"; then
    echo "✅ PM2: OK"
else
    echo "❌ PM2: FAIL"
    exit 1
fi

echo "🎉 Sistema saludable"
EOF

    chmod +x "$DEVELOPMENT_PATH/scripts/health_check.sh"
    
    log "✅ Health check configurado"
}

# 📚 CREAR DOCUMENTACIÓN
create_documentation() {
