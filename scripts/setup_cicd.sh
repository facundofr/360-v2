    cat > "$DEVELOPMENT_PATH/CI_CD_DOCUMENTATION.md" << 'EOF'
# 🚀 CI/CD Pipeline - Cober360

## 📋 Descripción General

Este documento describe el pipeline de CI/CD (Integración y Despliegue Continuo) implementado para Cober360.

## 🌿 Estructura de Ramas

- **`main`**: Rama principal de desarrollo (staging)
- **`develop`**: Rama de desarrollo activo
- **`production`**: Rama de producción

## 🔄 Flujo de Trabajo

### 1. Desarrollo
```bash
# Trabajar en rama develop
git checkout develop
git pull origin develop

# Hacer cambios y commits
git add .
git commit -m "feat: nueva funcionalidad"
git push origin develop
```

### 2. Staging/Testing
```bash
# Merge a main para testing
git checkout main
git merge develop
git push origin main
```

### 3. Producción
```bash
# Merge a production para deploy
git checkout production
git merge main
git push origin production
```

## 🤖 Automatización

### GitHub Actions
- **Testing**: Se ejecuta en push a `main` y `develop`
- **Build**: Se ejecuta en push a `main` y `production`
- **Deploy**: Se ejecuta en push a `production`

### Scripts Locales
```bash
# Deploy manual
./scripts/deploy.sh

# Rollback
./scripts/deploy.sh rollback

# Health check
./scripts/deploy.sh health
```

## 🏥 Monitoreo

### Health Checks
- API: `http://localhost:4000/health`
- Database: Verificación de conexión MySQL
- PM2: Estado de procesos

### Logs
- Deploy logs: `/var/log/deploy-cober360.log`
- Application logs: `backend/logs/`
- PM2 logs: `pm2 logs`

## 🔧 Configuración

### Variables de Entorno
- Desarrollo: `backend/.env`
- Producción: `backend/.env` (en servidor de producción)

### Dependencias
```bash
# Backend
cd backend && npm ci

# Frontend  
cd frontend && npm ci && npm run build
```

## 🚨 Troubleshooting

### Problemas Comunes

1. **Deploy falla**
   ```bash
   ./scripts/deploy.sh rollback
   ```

2. **Tests fallan**
   ```bash
   cd backend && npm test
   cd frontend && npm test
   ```

3. **API no responde**
   ```bash
   pm2 restart all
   ```

### Contacto
- DevOps Team: devops@cober.online
- Sistema de tickets: GitHub Issues

## 📊 Métricas

- **Deployment frequency**: Diario
- **Lead time**: < 1 hora
- **MTTR**: < 15 minutos
- **Change failure rate**: < 5%
EOF

    log "✅ Documentación creada"
}

# 🎯 FUNCIÓN PRINCIPAL
main() {
    log "🚀 Iniciando configuración de CI/CD para Cober360"
    
    # Verificar que los directorios existen
    if [ ! -d "$DEVELOPMENT_PATH" ]; then
        error "Directorio de desarrollo no encontrado: $DEVELOPMENT_PATH"
    fi
    
    if [ ! -d "$PRODUCTION_PATH" ]; then
        error "Directorio de producción no encontrado: $PRODUCTION_PATH"
    fi
    
    # Ejecutar configuración
    setup_development
    setup_production
    setup_develop
    create_env_files
    setup_npm_scripts
    create_dockerfile
    setup_monitoring
    create_documentation
    
    log "🎉 Configuración de CI/CD completada"
    
    echo ""
    echo "📋 PRÓXIMOS PASOS:"
    echo "1. Revisar y actualizar archivos .env con tus credenciales"
    echo "2. Configurar secretos en GitHub Actions"
    echo "3. Ejecutar primer deployment: ./scripts/deploy.sh"
    echo "4. Verificar health check: ./scripts/health_check.sh"
    echo ""
    echo "📚 Ver documentación completa en: CI_CD_DOCUMENTATION.md"
}

# 📋 AYUDA
show_help() {
    echo "🔧 Script de Configuración de CI/CD para Cober360"
    echo ""
    echo "Uso: $0 [OPCIÓN]"
    echo ""
    echo "Opciones:"
    echo "  setup      Configuración completa (por defecto)"
    echo "  dev        Solo configurar desarrollo"
    echo "  prod       Solo configurar producción"
    echo "  help       Mostrar esta ayuda"
    echo ""
}

# 🎯 MANEJO DE ARGUMENTOS
case "${1:-setup}" in
    "setup")
        main
        ;;
    "dev")
        setup_development
