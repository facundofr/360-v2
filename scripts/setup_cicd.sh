#!/bin/bash

# 🔧 Script de Configuración de Repositorio para CI/CD
# Configura las ramas y estructura para deployment continuo

set -e

# 🎨 COLORES
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

log() {
    echo -e "${GREEN}[$(date +'%H:%M:%S')] $1${NC}"
}

warn() {
    echo -e "${YELLOW}[$(date +'%H:%M:%S')] WARNING: $1${NC}"
}

error() {
    echo -e "${RED}[$(date +'%H:%M:%S')] ERROR: $1${NC}"
    exit 1
}

info() {
    echo -e "${BLUE}[$(date +'%H:%M:%S')] INFO: $1${NC}"
}

# 📂 PATHS
DEVELOPMENT_PATH="/var/www/cober360"
PRODUCTION_PATH="/var/www/cober360-produccion"

# 🔧 CONFIGURAR DESARROLLO (rama main)
setup_development() {
    log "🔧 Configurando entorno de desarrollo..."
    
    cd "$DEVELOPMENT_PATH"
    
    # Asegurar que estamos en main
    git checkout main 2>/dev/null || git checkout -b main
    
    # Limpiar cambios no commiteados si es necesario
    if [ "$(git status --porcelain)" ]; then
        warn "Hay cambios sin commitear en desarrollo"
        read -p "¿Commitear todos los cambios pendientes? (y/n): " -n 1 -r
        echo
        if [[ $REPLY =~ ^[Yy]$ ]]; then
            git add .
            git commit -m "feat: cambios pendientes antes de configurar CI/CD

- Configuración automática de CI/CD
- Sincronización de cambios pendientes
- Preparación para deployment automatizado

Generated by: setup_cicd.sh"
        else
            info "Guardando cambios en stash..."
            git stash push -m "Cambios pendientes - configuración CI/CD $(date)"
        fi
    fi
    
    # Push de main al repositorio
    git push origin main || warn "No se pudo hacer push a main"
    
    log "✅ Desarrollo configurado en rama 'main'"
}

# 🏭 CONFIGURAR PRODUCCIÓN (rama production)
setup_production() {
    log "🏭 Configurando entorno de producción..."
    
    cd "$PRODUCTION_PATH"
    
    # Crear y cambiar a rama production
    git checkout main 2>/dev/null || git checkout -b main
    
    # Limpiar cambios si es necesario
    if [ "$(git status --porcelain)" ]; then
        warn "Hay cambios sin commitear en producción"
        git add .
        git commit -m "prod: estado actual de producción

- Captura del estado de producción actual
- Preparación para rama production
- Configuración automática de CI/CD

Generated by: setup_cicd.sh"
    fi
    
    # Crear rama production desde el estado actual
    git checkout -b production 2>/dev/null || git checkout production
    
    # Push de production al repositorio
    git push origin production || git push --set-upstream origin production
    
    log "✅ Producción configurada en rama 'production'"
}

# 🔄 CREAR RAMA DEVELOP
setup_develop() {
    log "🔄 Configurando rama develop..."
    
    cd "$DEVELOPMENT_PATH"
    
    # Crear rama develop desde main
    git checkout main
    git checkout -b develop 2>/dev/null || git checkout develop
    git push origin develop || git push --set-upstream origin develop
    
    log "✅ Rama 'develop' creada y configurada"
}

